import { describe, expect, it } from 'vitest'
import { EMPTY_CONFIG, hashText, importRules, lineChanges, planTarget, renderTarget, RULE_TARGETS, type RulesConfig } from '@shared/rules'

const target = (id: string) => RULE_TARGETS.find((t) => t.id === id)!
const SOURCE = '# Rules\n\nRun npm test before you finish.'

describe('renderTarget', () => {
  it('writes the rules under a generated-file header', () => {
    const text = renderTarget('agents', SOURCE, EMPTY_CONFIG)
    expect(text.startsWith('<!-- Generated by sldev-io')).toBe(true)
    expect(text).toContain('Run npm test')
  })

  it('points Claude and Gemini at AGENTS.md instead of repeating it', () => {
    expect(renderTarget('claude', SOURCE, EMPTY_CONFIG)).toContain('@AGENTS.md')
    expect(renderTarget('claude', SOURCE, EMPTY_CONFIG)).not.toContain('Run npm test')
  })

  it('writes the full rules to CLAUDE.md when AGENTS.md is off', () => {
    expect(renderTarget('claude', SOURCE, { ...EMPTY_CONFIG, targets: { agents: false } })).toContain('Run npm test')
  })

  it('gives Cursor an always-applied rule', () => {
    expect(renderTarget('cursor', SOURCE, EMPTY_CONFIG)).toMatch(/^---\ndescription: .*\nalwaysApply: true\n---/)
  })
})

describe('planTarget', () => {
  const next = renderTarget('agents', SOURCE, EMPTY_CONFIG)
  const written = (text: string): RulesConfig => ({ targets: {}, written: { 'AGENTS.md': hashText(text) } })

  it('creates a missing file', () => {
    expect(planTarget(target('agents'), SOURCE, null, EMPTY_CONFIG).status).toBe('create')
  })

  it('is in sync when the file matches', () => {
    expect(planTarget(target('agents'), SOURCE, next, EMPTY_CONFIG).status).toBe('in-sync')
  })

  it('updates a file it wrote last time', () => {
    const old = renderTarget('agents', 'old rules', EMPTY_CONFIG)
    const p = planTarget(target('agents'), SOURCE, old, written(old))
    expect(p.status).toBe('update')
    expect(p.added).toBeGreaterThan(0)
  })

  it('never silently overwrites a hand-edited or foreign file', () => {
    const old = renderTarget('agents', 'old rules', EMPTY_CONFIG)
    expect(planTarget(target('agents'), SOURCE, old + 'my edit\n', written(old)).status).toBe('hand-edited')
    expect(planTarget(target('agents'), SOURCE, '# my own AGENTS.md\n', EMPTY_CONFIG).status).toBe('hand-edited')
  })

  it('skips targets that are switched off', () => {
    expect(planTarget(target('copilot'), SOURCE, null, { targets: { copilot: false }, written: {} }).status).toBe('off')
  })
})

describe('importRules', () => {
  it('takes each distinct text once, without imports or front matter', () => {
    const out = importRules([
      { path: 'AGENTS.md', text: '# Agents\nUse tabs.\n' },
      { path: 'CLAUDE.md', text: '@AGENTS.md\n' },
      { path: 'GEMINI.md', text: '# Agents\nUse tabs.\n' },
      { path: '.cursor/rules/x.mdc', text: '---\nalwaysApply: true\n---\nPrefer small PRs.\n' },
      { path: '.github/copilot-instructions.md', text: null }
    ])
    expect(out).toBe('# Agents\nUse tabs.\n\n<!-- from .cursor/rules/x.mdc -->\n\nPrefer small PRs.\n')
  })

  it('starts a template when there is nothing to import', () => {
    expect(importRules([])).toContain('# Project rules')
  })
})

describe('lineChanges', () => {
  it('counts lines added and removed', () => {
    expect(lineChanges('a\nb\nc', 'a\nc\nd\ne')).toEqual({ added: 2, removed: 1 })
  })
})

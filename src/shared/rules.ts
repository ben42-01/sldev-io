/**
 * Rules sync: one `.sldev/rules.md` written out as the file each agent reads. Hashes of what was
 * written are kept in `.sldev/rules.json`, so a target someone edited by hand is never overwritten
 * without asking.
 */

export const RULES_SOURCE = '.sldev/rules.md'
export const RULES_CONFIG = '.sldev/rules.json'

export interface RuleTarget {
  id: string
  path: string
  /** who reads it */
  readers: string
}

export const RULE_TARGETS: RuleTarget[] = [
  { id: 'agents', path: 'AGENTS.md', readers: 'Codex, OpenCode, Cursor, Copilot and most other agents' },
  { id: 'claude', path: 'CLAUDE.md', readers: 'Claude Code' },
  { id: 'gemini', path: 'GEMINI.md', readers: 'Gemini CLI' },
  { id: 'cursor', path: '.cursor/rules/sldev.mdc', readers: 'Cursor' },
  { id: 'copilot', path: '.github/copilot-instructions.md', readers: 'GitHub Copilot' }
]

export interface RulesConfig {
  /** target id → on/off; missing = on */
  targets: Record<string, boolean>
  /** target path → hash of the text sldev-io last wrote there */
  written: Record<string, string>
}

export const EMPTY_CONFIG: RulesConfig = { targets: {}, written: {} }

export type TargetStatus = 'off' | 'in-sync' | 'create' | 'update' | 'hand-edited'

export interface TargetPlan {
  target: RuleTarget
  status: TargetStatus
  next: string
  added: number
  removed: number
}

const HEADER = '<!-- Generated by sldev-io from .sldev/rules.md. Edit that file and sync, not this one. -->'

export const isOn = (c: RulesConfig, id: string): boolean => c.targets[id] !== false

/** Claude Code and Gemini CLI follow `@file` imports, so they point at AGENTS.md when it's written. */
export function renderTarget(id: string, source: string, config: RulesConfig): string {
  const body = source.trim()
  if ((id === 'claude' || id === 'gemini') && isOn(config, 'agents')) return `${HEADER}\n\n@AGENTS.md\n`
  if (id === 'cursor') return `---\ndescription: Project rules (from .sldev/rules.md)\nalwaysApply: true\n---\n\n${HEADER}\n\n${body}\n`
  return `${HEADER}\n\n${body}\n`
}

/** FNV-1a: enough to notice a hand edit, and the same in every process. */
export function hashText(s: string): string {
  let h = 0x811c9dc5
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return (h >>> 0).toString(16).padStart(8, '0')
}

/** Lines only in `b` and lines only in `a`, as a quick measure of the change. */
export function lineChanges(a: string, b: string): { added: number; removed: number } {
  const count = (lines: string[]): Map<string, number> => lines.reduce((m, l) => m.set(l, (m.get(l) ?? 0) + 1), new Map<string, number>())
  const ca = count(a.split('\n'))
  const cb = count(b.split('\n'))
  let added = 0
  let removed = 0
  for (const [l, n] of cb) added += Math.max(0, n - (ca.get(l) ?? 0))
  for (const [l, n] of ca) removed += Math.max(0, n - (cb.get(l) ?? 0))
  return { added, removed }
}

export function planTarget(target: RuleTarget, source: string, current: string | null, config: RulesConfig): TargetPlan {
  const next = renderTarget(target.id, source, config)
  const base = { target, next, ...lineChanges(current ?? '', next) }
  if (!isOn(config, target.id)) return { ...base, status: 'off', added: 0, removed: 0 }
  if (current === null) return { ...base, status: 'create' }
  if (current === next) return { ...base, status: 'in-sync', added: 0, removed: 0 }
  const last = config.written[target.path]
  return { ...base, status: last && hashText(current) === last ? 'update' : 'hand-edited' }
}

/** A first rules.md from whatever agent files the project already has: each distinct text once. */
export function importRules(files: Array<{ path: string; text: string | null }>): string {
  const seen = new Set<string>()
  const parts: string[] = []
  for (const f of files) {
    if (!f.text) continue
    const text = f.text
      .replace(/^---\n[\s\S]*?\n---\n/, '')
      .replace(HEADER, '')
      .split('\n')
      .filter((l) => !/^@\S+$/.test(l.trim()))
      .join('\n')
      .trim()
    if (!text || seen.has(text)) continue
    seen.add(text)
    parts.push(parts.length ? `<!-- from ${f.path} -->\n\n${text}` : text)
  }
  return parts.length ? `${parts.join('\n\n')}\n` : '# Project rules\n\nHow agents should work in this project: commands, conventions, things that broke before.\n'
}

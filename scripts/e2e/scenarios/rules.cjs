// Rules sync: create .sldev/rules.md from existing agent files, sync, then keep a hand edit safe.
const fs = require('fs')
const path = require('path')

module.exports = async (h) => {
  const f = (p) => path.join(h.fixture, p)
  fs.writeFileSync(f('AGENTS.md'), '# Agents\n\nRun npm test before finishing.\n')
  await h.openFixture()
  await h.click('.right-tab[title^="Skills"]')
  await h.wait(600)
  await h.click('.tabs button', 'Rules')
  await h.wait(500)
  h.expect(await h.js(`!!document.querySelector('.rules .btn.primary')?.textContent.includes('Create')`), 'offers to create rules.md')
  await h.shot('0-empty')
  // creating opens the file in the editor; there's no editor in the harness, so ignore that
  await h.js(`document.querySelector('.rules .btn.primary').click()`)
  await h.until(() => fs.existsSync(f('.sldev/rules.md')), 5000)
  h.expect(fs.readFileSync(f('.sldev/rules.md'), 'utf8').includes('Run npm test'), 'rules.md starts from the existing AGENTS.md')
  h.expect(fs.readFileSync(f('AGENTS.md'), 'utf8') === '# Agents\n\nRun npm test before finishing.\n', 'creating rules.md changes no agent file')
  await h.wait(500)
  const chips = () => h.js(`Object.fromEntries([...document.querySelectorAll('.rule-row')].map(r => [r.querySelector('.rt-name').textContent, r.querySelector('.rule-chip').textContent]))`)
  let c = await chips()
  h.expect(c['AGENTS.md'] === 'edited by hand', 'the existing AGENTS.md counts as hand-edited')
  h.expect(c['CLAUDE.md'] === 'will create' && c['.github/copilot-instructions.md'] === 'will create', 'missing targets will be created')
  await h.shot('1-plan')

  // sync writes the new files and leaves the hand-written AGENTS.md alone
  await h.click('.rules .btn.primary', 'Sync')
  await h.wait(800)
  h.expect(fs.readFileSync(f('CLAUDE.md'), 'utf8').includes('@AGENTS.md'), 'CLAUDE.md imports AGENTS.md')
  h.expect(fs.readFileSync(f('.cursor/rules/sldev.mdc'), 'utf8').includes('alwaysApply: true'), 'Cursor rule written')
  h.expect(!fs.readFileSync(f('AGENTS.md'), 'utf8').includes('Generated by sldev-io'), 'hand-written AGENTS.md left alone')

  // overwrite it on request, then a rules.md change updates every generated file
  await h.click('.rule-row .link', 'overwrite')
  await h.wait(800)
  h.expect(fs.readFileSync(f('AGENTS.md'), 'utf8').includes('Generated by sldev-io'), 'overwrite writes AGENTS.md')
  fs.appendFileSync(f('.sldev/rules.md'), '\nUse pnpm, not npm.\n')
  await h.click('.rules .icon-btn[title="Rescan"]')
  await h.wait(600)
  c = await chips()
  h.expect(c['AGENTS.md'] === 'will update' && c['.github/copilot-instructions.md'] === 'will update', 'rules.md edits show as updates')
  h.expect(c['CLAUDE.md'] === 'in sync', 'CLAUDE.md stays a pointer, so it stays in sync')
  await h.click('.rules .btn.primary', 'Sync')
  await h.wait(800)
  h.expect(fs.readFileSync(f('.github/copilot-instructions.md'), 'utf8').includes('Use pnpm'), 'sync updates generated files')

  // a hand edit to a generated file is detected and not overwritten
  fs.appendFileSync(f('.github/copilot-instructions.md'), '\nmy own line\n')
  fs.appendFileSync(f('.sldev/rules.md'), '\nKeep PRs small.\n')
  await h.click('.rules .icon-btn[title="Rescan"]')
  await h.wait(600)
  c = await chips()
  h.expect(c['.github/copilot-instructions.md'] === 'edited by hand', 'a hand edit after a sync is caught')
  await h.click('.rules .btn.primary', 'Sync')
  await h.wait(800)
  h.expect(fs.readFileSync(f('.github/copilot-instructions.md'), 'utf8').includes('my own line'), 'and survives the next sync')
  await h.shot('2-after-sync')
}

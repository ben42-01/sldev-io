// The right sidebar (overview, agents, skills, workflows), terminal copy/paste, and the task script picker.
const fs = require('fs')
const path = require('path')

module.exports = async (h) => {
  const clipboard = { readText: () => h.js('window.api.clipboard.readText()'), writeText: (t) => h.js(`window.api.clipboard.writeText(${JSON.stringify(t)})`) }
  fs.writeFileSync(path.join(h.fixture, 'package.json'), JSON.stringify({ name: 'fixture', scripts: { build: 'tsc -p .', test: 'vitest run' } }))
  fs.mkdirSync(path.join(h.fixture, 'packages', 'api'), { recursive: true })
  fs.writeFileSync(path.join(h.fixture, 'packages', 'api', 'package.json'), JSON.stringify({ scripts: { start: 'node server.js' } }))
  await h.openFixture({ rightPanelVisible: true, rightPanelTab: 'overview' })

  h.expect(await h.js(`!!document.querySelector('.rightpanel .overview')`), 'right sidebar opens on the overview')
  h.expect(await h.js(`[...document.querySelectorAll('.activitybar:not(.right) .activity-btn')].every(b => !/Skills|Workflows|Agent Missions/.test(b.title))`), 'skills, workflows and missions left the left activity bar')
  await h.shot('0-overview')

  await h.click('.right-tab[title^="Agent Missions"]')
  await h.wait(300)
  h.expect(await h.js(`document.querySelector('.right-tab.on')?.title.startsWith('Agent Missions')`), 'agents tab switches')
  await h.shot('1-agents')
  await h.click('.right-tab[title^="GitHub Workflows"]')
  await h.wait(500)
  await h.shot('2-workflows')

  await h.click('.right-close')
  await h.wait(300)
  h.expect(await h.js(`!document.querySelector('.rightpanel') && !!document.querySelector('.activitybar.right')`), 'hiding leaves a slim rail')
  await h.shot('3-rail')
  await h.click('.activitybar.right .activity-btn[aria-label^="Skills"]')
  await h.wait(500)
  h.expect(await h.js(`document.querySelector('.right-tab.on')?.title.startsWith('Skills')`), 'a rail icon reopens on its tab')
  h.expect(await h.js(`window.api.settings.get().then(s => s.rightPanelVisible && s.rightPanelTab === 'skills')`), 'right sidebar state is saved')

  // terminal: right-click menu copies the selection and the whole output
  h.key('T', ['control', 'shift'])
  await h.wait(1500)
  h.type('echo copy-me-e2e\r')
  await h.wait(800)
  await clipboard.writeText('')
  const menu = () => h.js(`(() => { const m = document.querySelector('.terminal-mount'); const r = m.getBoundingClientRect(); m.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: r.left + 40, clientY: r.top + 40 })); return true })()`)
  await menu()
  await h.wait(200)
  h.expect(await h.js(`[...document.querySelectorAll('.ctx-item .ctx-label')].map(e => e.textContent).join(',') === 'Copy,Paste,Select all,Copy all output,Clear'`), 'terminal has a copy/paste menu')
  h.expect(await h.js(`document.querySelector('.ctx-item')?.disabled === true`), 'Copy is off without a selection')
  await h.shot('4-terminal-menu')
  await h.click('.ctx-item', 'Select all')
  await h.wait(200)
  await menu()
  await h.wait(200)
  await h.click('.ctx-item', 'Copy')
  h.expect(await h.until(async () => (await clipboard.readText()).includes('copy-me-e2e'), 3000), 'Copy puts the selection on the clipboard')
  await clipboard.writeText('')
  await menu()
  await h.wait(200)
  await h.click('.ctx-item', 'Copy all output')
  h.expect(await h.until(async () => (await clipboard.readText()).includes('echo copy-me-e2e'), 3000), 'Copy all output copies the scrollback')
  // Ctrl+C with a selection copies instead of interrupting
  await clipboard.writeText('')
  await menu()
  await h.wait(200)
  await h.click('.ctx-item', 'Select all')
  await h.wait(200)
  h.key('C', ['control'])
  h.expect(await h.until(async () => (await clipboard.readText()).includes('copy-me-e2e'), 3000), 'Ctrl+C copies a selection')

  // tasks: pick a package.json script, and the list follows the folder
  h.key('4', ['control', 'shift'])
  await h.wait(500)
  await h.click('button[title="New task"]')
  await h.wait(300)
  await h.click('.form .seg button', 'Shell')
  await h.until(() => h.js(`!!document.querySelector('.form select option[value="npm::test"]')`), 3000)
  h.expect(await h.js(`[...document.querySelectorAll('.form optgroup')].some(g => g.label === 'package.json')`), 'task editor lists the folder scripts')
  h.expect(await h.setValue('.form select', 'npm::test', `e.querySelector('optgroup')`), 'pick the test script')
  await h.wait(200)
  h.expect(await h.js(`document.querySelector('.form textarea.mono')?.value === 'npm run test' && document.querySelector('.form input[autofocus], .form .field input')?.value === 'test'`), 'picking fills the command and the name')
  await h.shot('5-task-scripts')
  await h.setValue('.form input[aria-label="Folder"]', 'packages/api')
  h.expect(await h.until(() => h.js(`!!document.querySelector('.form select option[value="npm::start"]') && !document.querySelector('.form select option[value="npm::test"]')`), 3000), 'changing the folder lists that package')
  await h.shot('6-task-folder')
}

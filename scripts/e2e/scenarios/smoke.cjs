// Welcome screen, terminal, split, command palette, settings.
const fs = require('fs')
const path = require('path')

module.exports = async (h) => {
  await h.shot('1-welcome')
  h.expect(await h.js(`document.querySelector('.welcome h1')?.textContent.includes('sldev-io')`), 'welcome shows the app name')
  await h.openFixture()
  // with a project open, the start screen takes a brief: Enter opens the New mission form with it
  h.expect(await h.until(() => h.js(`!!document.querySelector('.welcome .hero-form input')`), 3000), 'the start screen offers a brief box')
  await h.setValue('.welcome .hero-form input', 'Tidy the README')
  await h.js(`document.querySelector('.welcome .hero-form').requestSubmit()`)
  h.expect(await h.until(() => h.js(`document.querySelector('dialog[open] .mission-form textarea')?.value === 'Tidy the README'`), 2000), 'Enter opens New mission with the brief filled in')
  await h.shot('1b-welcome-brief')
  h.key('Escape')
  h.expect(await h.until(() => h.js(`!document.querySelector('dialog[open]')`), 2000), 'Esc closes it again')
  h.key('T', ['control', 'shift'])
  await h.wait(1500)
  // the WebGL renderer draws to a canvas, so check a side effect instead of DOM text
  h.type('echo e2e-ok > e2e-marker.txt\r')
  await h.wait(800)
  h.expect(fs.existsSync(path.join(h.fixture, 'e2e-marker.txt')), 'terminal runs commands in the project folder')
  h.key('D', ['control', 'shift'])
  await h.wait(1200)
  h.expect((await h.js(`document.querySelectorAll('.xterm').length`)) === 2, 'split opens a second terminal')
  await h.shot('2-terminals')
  h.key('P', ['control', 'shift'])
  await h.wait(400)
  h.type('settings')
  await h.wait(300)
  h.expect(await h.js(`!!document.querySelector('.palette .palette-item')`), 'command palette lists results')
  await h.shot('3-palette')
  h.key('Escape')
  h.key(',', ['control'])
  await h.wait(1000)
  h.expect(await h.js(`!!document.querySelector('.settings')`), 'settings panel opens')
  h.expect(await h.js(`[...document.querySelectorAll('.settings-nav button')].map(b => b.textContent).join().includes('Terminal,Editor,Agents')`), 'settings lists its sections as jump links')
  await h.shot('4-settings')
}

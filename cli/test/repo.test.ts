import { execFileSync } from 'child_process'
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, utimesSync, writeFileSync } from 'fs'
import { tmpdir } from 'os'
import { join } from 'path'
import { afterAll, describe, expect, it } from 'vitest'
import { closeContext } from '../../src/main/context'
import { memorySummary, projectRoot, recallNotes, rememberNote, rulesInit, rulesStatus, rulesSync } from '../src/repo'
import { claudeUsage, codexUsage } from '../src/usage'

const tmp = mkdtempSync(join(tmpdir(), 'sldev-cli-repo-'))
afterAll(() => {
  closeContext()
  rmSync(tmp, { recursive: true, force: true })
})

describe('repo commands', () => {
  const repo = join(tmp, 'repo')
  mkdirSync(join(repo, 'src'), { recursive: true })
  execFileSync('git', ['init', '-q'], { cwd: repo })

  it('finds the project from a subfolder', async () => {
    // the long path: on Windows the temp folder can come as an 8.3 short name (RUNNER~1), git gives the long one
    expect(await projectRoot(join(repo, 'src'))).toBe(realpathSync.native(repo))
    expect(await projectRoot(tmp)).toBe(tmp)
  })

  it('starts rules from AGENTS.md, syncs them, and leaves a hand-edited file alone', async () => {
    writeFileSync(join(repo, 'AGENTS.md'), '# Rules\n\nRun npm test before you finish.\n')
    expect(await rulesStatus(repo)).toContain('sldev rules init')
    await rulesInit(repo)
    expect(readFileSync(join(repo, '.sldev/rules.md'), 'utf8')).toContain('Run npm test')
    const out = await rulesSync(repo, [])
    expect(out).toMatch(/wrote\s+CLAUDE\.md/)
    expect(readFileSync(join(repo, 'CLAUDE.md'), 'utf8')).toContain('@AGENTS.md')
    // AGENTS.md was there before sldev wrote it: hand-edited, kept until --overwrite
    expect(out).toMatch(/skipped AGENTS\.md/)
    expect(await rulesStatus(repo)).toMatch(/AGENTS\.md\s+edited by hand/)
    await rulesSync(repo, ['agents'])
    expect(readFileSync(join(repo, 'AGENTS.md'), 'utf8')).toContain('Generated by sldev-io')
  })

  it('remembers a note and finds it again', async () => {
    expect(await memorySummary(repo)).toContain('No project memory yet')
    await rememberNote(repo, 'The parser tests need TZ=UTC', ['src/parser.ts'])
    const mem = readFileSync(join(repo, '.sldev/memory.md'), 'utf8')
    expect(mem).toMatch(/- \d{4}-\d\d-\d\d: The parser tests need TZ=UTC \(sldev CLI\) · files: src\/parser\.ts/)
    expect(await memorySummary(repo)).toContain('1 entry')
    const data = join(tmp, 'data')
    expect(await recallNotes(data, repo, 'parser tests')).toContain('TZ=UTC')
    expect(await recallNotes(data, repo, '', 'src/parser.ts')).toContain('TZ=UTC')
    await expect(recallNotes(data, repo, '')).rejects.toThrow(/topic/)
  })
})

describe('usage from local logs', () => {
  it('counts Claude messages written in the period and Codex sessions started in it', async () => {
    const claude = join(tmp, 'claude', 'projects', 'p')
    mkdirSync(claude, { recursive: true })
    const msg = (id: string, at: string, out: number) => JSON.stringify({ type: 'assistant', timestamp: at, message: { id, model: 'claude-sonnet-4-5', usage: { input_tokens: 10, output_tokens: out } } })
    writeFileSync(join(claude, 's.jsonl'), [msg('a', '2026-11-01T10:00:00Z', 1000), msg('b', '2026-11-05T10:00:00Z', 50)].join('\n') + '\n')
    const old = join(claude, 'old.jsonl')
    writeFileSync(old, msg('c', '2026-10-01T10:00:00Z', 999) + '\n')
    utimesSync(old, new Date('2026-10-01'), new Date('2026-10-01'))
    const since = Date.parse('2026-11-05T00:00:00Z')
    const c = await claudeUsage(since, { CLAUDE_CONFIG_DIR: join(tmp, 'claude') })
    expect(c.sessions).toBe(1)
    expect(c.usage.output).toBe(50)
    expect(c.usage.cost).toBeGreaterThan(0)

    const day = join(tmp, 'codex', 'sessions', '2026', '11', '05')
    mkdirSync(day, { recursive: true })
    writeFileSync(
      join(day, 'r.jsonl'),
      [
        JSON.stringify({ type: 'session_meta', payload: { cwd: '/r', timestamp: '2026-11-05T09:00:00Z' } }),
        JSON.stringify({ type: 'turn_context', payload: { model: 'gpt-5' } }),
        JSON.stringify({ type: 'event_msg', payload: { type: 'token_count', info: { total_token_usage: { input_tokens: 100, cached_input_tokens: 40, output_tokens: 7 } } } })
      ].join('\n') + '\n'
    )
    const x = await codexUsage(since, { CODEX_HOME: join(tmp, 'codex') })
    expect(x.sessions).toBe(1)
    expect(x.usage).toMatchObject({ input: 60, cacheRead: 40, output: 7 })
  })
})
